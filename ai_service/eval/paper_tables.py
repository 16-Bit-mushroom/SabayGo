#!/usr/bin/env python3
"""
Emit the evaluation tables in a form that can be pasted into the manuscript.

Separate from evaluate.py on purpose. That script's report is a lab record:
wide, verbose, and full of notes to ourselves. A paper needs short captions,
narrow columns and no asides. Rather than hand-copy numbers between the two
-- which is how a figure in a paper ends up disagreeing with the data behind
it -- both read the same per-image CSV.

Re-run this after any change to the evaluation set (the staged van shoot,
for instance) and replace the tables in the .docx wholesale.

    python eval/paper_tables.py --csv docs/benchmarks/ai_count_<date>.csv
"""

from __future__ import annotations

import argparse
import csv
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import metrics  # noqa: E402


def load(path, condition="original", conf=None):
    rows = [r for r in csv.DictReader(open(path, encoding="utf-8"))
            if r["condition"] == condition]
    if conf is None:
        confs = sorted({float(r["conf"]) for r in rows})
        conf = 0.45 if 0.45 in confs else confs[len(confs) // 2]
    rows = [r for r in rows if float(r["conf"]) == conf]
    err = np.array([int(r["error"]) for r in rows], dtype=int)
    true = np.array([int(r["true_count"]) for r in rows], dtype=int)
    ms = np.array([float(r["inference_ms"]) for r in rows])
    return err, true, ms, conf, rows


def p(x):
    return f"{x * 100:.1f}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", required=True)
    args = ap.parse_args()

    err, true, ms, conf, _ = load(args.csv)
    all_rows = list(csv.DictReader(open(args.csv, encoding="utf-8")))
    confs = sorted({float(r["conf"]) for r in all_rows})

    print(f"% generated by eval/paper_tables.py from {os.path.basename(args.csv)}")
    print(f"% operating threshold = {conf}; n = {err.size} images\n")

    # ---- Table B: counting accuracy by occupancy --------------------------
    print("TABLE B. Counting accuracy by cabin occupancy\n")
    print("| Passengers present | Images | MAE | RMSE | Mean signed error | "
          "Exact count (%) | Within +/-1 (%) |")
    print("|---|---|---|---|---|---|---|")
    for label, lo, hi in metrics.BANDS:
        mask = (true >= lo) & (true <= hi)
        if not mask.any():
            continue
        m = metrics.counting(err[mask])
        print(f"| {label} | {m['n']} | {m['mae']:.2f} | {m['rmse']:.2f} | "
              f"{m['bias']:+.2f} | {p(m['exact'])} | {p(m['within1'])} |")
    o = metrics.counting(err)
    print(f"| **All** | **{o['n']}** | **{o['mae']:.2f}** | **{o['rmse']:.2f}** | "
          f"**{o['bias']:+.2f}** | **{p(o['exact'])}** | **{p(o['within1'])}** |")

    # ---- Table C: reconciliation performance ------------------------------
    print("\n\nTABLE C. Reconciliation performance by cabin occupancy\n")
    print("| Passengers present | Images | False alarm, D!=0 (%) | "
          "False alarm, D>0 (%) | Detects 1 hidden (%) | Detects 2 hidden (%) |")
    print("|---|---|---|---|---|---|")
    for label, lo, hi in metrics.BANDS:
        mask = (true >= lo) & (true <= hi)
        if not mask.any():
            continue
        m = metrics.leakage(err[mask])
        print(f"| {label} | {m['n']} | {p(m['false_alarm_strict'])} | "
              f"{p(m['false_alarm_leakage'])} | {p(m['detect_leakage_k1'])} | "
              f"{p(m['detect_leakage_k2'])} |")
    lk = metrics.leakage(err)
    print(f"| **All** | **{lk['n']}** | **{p(lk['false_alarm_strict'])}** | "
          f"**{p(lk['false_alarm_leakage'])}** | "
          f"**{p(lk['detect_leakage_k1'])}** | "
          f"**{p(lk['detect_leakage_k2'])}** |")

    # ---- Table D: threshold sensitivity -----------------------------------
    if len(confs) > 1:
        print("\n\nTABLE D. Confidence threshold sensitivity\n")
        print("| Threshold | MAE | Exact count (%) | Overcount rate (%) | "
              "Undercount rate (%) | False alarm, D!=0 (%) | "
              "False alarm, D>0 (%) | Detects 1, D>0 (%) |")
        print("|---|---|---|---|---|---|---|---|")
        for c in confs:
            e, _, _, _, _ = load(args.csv, conf=c)
            cm, cl = metrics.counting(e), metrics.leakage(e)
            star = " *" if c == conf else ""
            print(f"| {c}{star} | {cm['mae']:.2f} | {p(cm['exact'])} | "
                  f"{p(cl['false_over'])} | {p(cl['false_under'])} | "
                  f"{p(cl['false_alarm_strict'])} | "
                  f"{p(cl['false_alarm_leakage'])} | "
                  f"{p(cl['detect_leakage_k1'])} |")
        print("\n* deployed value")

    # ---- Latency ----------------------------------------------------------
    lat = metrics.latency(ms)
    # The maximum is the first inference of the run: it includes one-off
    # lazy initialisation inside the framework and is not a per-audit cost.
    warm = metrics.latency(np.sort(ms)[:-1])
    print(f"\n\nLATENCY (n={lat['n']}): mean {lat['mean']:.0f} ms, "
          f"median {lat['median']:.0f} ms, p95 {lat['p95']:.0f} ms")
    print(f"excluding the first (warm-up) inference: max {warm['max']:.0f} ms")
    return 0


if __name__ == "__main__":
    sys.exit(main())
